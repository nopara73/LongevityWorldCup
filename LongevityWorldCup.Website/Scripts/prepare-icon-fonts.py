"""Rebuild LWC's icon fonts and CSS character ranges with fonttools==4.61.1 and brotli==1.2.0."""

import hashlib
import re
import subprocess
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


SITE = Path(__file__).resolve().parents[1]
VENDOR = SITE / "wwwroot/vendor/font-awesome/6.7.2"
ICON_CLASS = re.compile(r"\bfa-[a-z0-9-]+")
CSS_CHARACTER = re.compile(r"""["']\\([e-fE-F][0-9a-fA-F]{3})["']""")
ICON_RULE = re.compile(r'([^{}]+)\{--fa:"\\([0-9a-f]+)"\}')
FACES_START = "/* LWC icon faces generated by Scripts/prepare-icon-fonts.py. */"
FACES_END = "/* End LWC icon faces. */"


def used_characters():
    paths = subprocess.check_output(
        ["git", "ls-files", "-z", "--", "*.cs", "*.ts", "*.js", "*.html", "*.css",
         ":(exclude)wwwroot/vendor/**", ":(exclude)wwwroot/assets/**"],
        cwd=SITE,
    ).decode("utf-8").split("\0")
    classes = set()
    characters = set()
    for relative in filter(None, paths):
        source = (SITE / relative).read_text(encoding="utf-8-sig")
        classes.update(ICON_CLASS.findall(source))
        characters.update(int(value, 16) for value in CSS_CHARACTER.findall(source))

    css = (VENDOR / "css/all.min.css").read_text(encoding="utf-8")
    for selectors, codepoint in ICON_RULE.findall(css):
        if not classes.isdisjoint(ICON_CLASS.findall(selectors)):
            characters.add(int(codepoint, 16))
    return characters


def unicode_ranges(characters):
    ranges = []
    for code in sorted(characters):
        if ranges and code == ranges[-1][1] + 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def font_face(family, weight, sources, characters):
    return f"""@font-face {{
    font-family: "{family}";
    font-style: normal;
    font-weight: {weight};
    font-display: block;
    src: {sources};
    unicode-range: {unicode_ranges(characters)};
}}"""


def write_font(style, weight, characters):
    directory = VENDOR / "webfonts"
    original = f"fa-{style}-{weight}"
    with TTFont(directory / f"{original}.woff2", recalcTimestamp=False) as font:
        catalog = set(font.getBestCmap())
        common = characters & catalog
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=common)
        subsetter.subset(font)

        # Give derivatives their own family and PostScript names. Keep upstream
        # copyright, version and license records alongside the original files.
        family = "LWC Icon Brands" if style == "brands" else "LWC Icons"
        subfamily = "Solid" if style == "solid" else "Regular"
        full_name = f"{family} {subfamily}"
        postscript = f"{family.replace(' ', '')}-{subfamily}"
        names = {1: family, 2: subfamily, 3: f"{postscript}-6.7.2",
                 4: full_name, 6: postscript, 16: family, 17: subfamily}
        for record in font["name"].names:
            if record.nameID in names:
                record.string = names[record.nameID].encode(record.getEncoding())

        target = directory / f"lwc-{style}.woff2"
        font.save(target)
        print(f"{target.name}: {len(common)} characters, {target.stat().st_size:,} bytes")

    version = hashlib.sha256(target.read_bytes()).hexdigest()[:16]
    original_sources = f'url("../webfonts/{original}.woff2") format("woff2"), url("../webfonts/{original}.ttf") format("truetype")'
    compact_source = f'url("../webfonts/{target.name}?v={version}") format("woff2")'
    # Explicit, disjoint ranges prevent browsers from probing the full font for
    # missing characters or font metrics while rendering only common symbols.
    return [
        font_face(family, weight, original_sources, catalog - common),
        # Space selects the inline line-box metrics even though it has no icon.
        font_face(family, weight, f"{compact_source}, {original_sources}", common | {0x20}),
    ]


if __name__ == "__main__":
    used = used_characters()
    stylesheet = VENDOR / "css/all.min.css"
    before, found_start, rest = stylesheet.read_text(encoding="utf-8").partition(FACES_START)
    _, found_end, after = rest.partition(FACES_END)
    if not (found_start and found_end):
        raise ValueError("The LWC face markers are missing from the stylesheet")
    faces = []
    for face, weight in (("solid", 900), ("regular", 400), ("brands", 400)):
        faces.extend(write_font(face, weight, used))
    stylesheet.write_text(before + "\n".join([FACES_START, *faces, FACES_END]) + after,
                          encoding="utf-8", newline="\n")
